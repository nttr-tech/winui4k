def prop_value(value):
    value = value.replace("\\", "\\\\").replace("\n", "\\n")
    return "\\" + value if value.startswith(" ") else value


MARKER = "# --- generated by tools/gen_cad_ribbon.py (do not edit below this line by hand)\n"
resources = os.path.dirname(os.path.abspath(dst)).replace(os.sep, "/").replace("/src/main/kotlin/", "/src/main/resources/")
for name, pick in (("messages.properties", 0), ("messages_ja.properties", 1)):
    path = os.path.join(resources, name)
    old = io.open(path, encoding="utf-8").read() if os.path.exists(path) else ""
    head = old.split(MARKER)[0].rstrip("\n")
    body = "".join("%s=%s\n" % (k, prop_value(v[pick])) for k, v in MESSAGES.items())
    os.makedirs(resources, exist_ok=True)
    io.open(path, "w", encoding="utf-8", newline="").write((head + "\n\n" if head else "") + MARKER + body)
