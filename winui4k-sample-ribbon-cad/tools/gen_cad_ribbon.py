"""Generates Kotlin that builds the WinUI4K model from the ribbon (tabs) of CadPage.xaml of the RibbonSpace CAD demo.

Text shown on screen becomes Messages.get("ribbon.…"), and English (as in the XAML) and Japanese (cad_ja.py, cad_tips_ja.py) are written to
messages.properties and messages_ja.properties in <the resources of the same package as dst>,
after the line "# --- generated by tools/gen_cad_ribbon.py" (the hand-written strings before that line are kept).
"""
import html
import io
import os
import re
import sys
import xml.etree.ElementTree as ET

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from cad_ja import JA  # noqa: E402
from cad_tips_ja import TIPS_JA  # noqa: E402

src, icons_kt, art_kt, dst = sys.argv[1:5]

CAD_ICONS = set(re.findall(r"const val (\w+)", io.open(icons_kt, encoding="utf-8").read()))
CAD_ART = set(re.findall(r"const val (\w+)", io.open(art_kt, encoding="utf-8").read()))
missing = set()


def snake(name):
    s = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name)
    s = re.sub(r"(?<=[A-Z])(?=[A-Z][a-z])", "_", s)
    return s.upper()


raw = io.open(src, encoding="utf-8").read()
raw = re.sub(r'\sxmlns(:\w+)?="[^"]*"', "", raw)
raw = re.sub(r"\{cad:CadIcon Name=(\w+)\}", r"@\1", raw)
raw = re.sub(r"<(/?)(\w+):(\w+)", r"<\1\2_\3", raw)
raw = re.sub(r"\s(\w+):(\w+)=", r" \1_\2=", raw)
root = ET.fromstring(raw)


def kstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("$", "\\$") + '"'


def ja(text):
    if text is None:
        return None
    if text in JA:
        return JA[text]
    missing.add(text)
    return text


# Screen text key -> (English, Japanese). Written to the properties in generation order
MESSAGES = {}


def key_part(value):
    return re.sub(r"[^a-z0-9]+", ".", value.lower()).strip(".")


def msg(key, en, ja_text):
    """The string as is if English and Japanese are the same (symbols, proper nouns, etc.), otherwise the Kotlin expression Messages.get(key)."""
    if en == ja_text:
        return kstr(en)
    key = "ribbon." + ".".join(key_part(p) for p in key.split("|"))
    base, n = key, 2
    while key in MESSAGES and MESSAGES[key] != (en, ja_text):
        key, n = "%s.v%d" % (base, n), n + 1
    MESSAGES[key] = (en, ja_text)
    return 'Messages.get("%s")' % key


def label(key, en, ja_text=None):
    """The Messages.get expression for a translated English label of the XAML."""
    return msg(key, en, ja_text if ja_text is not None else ja(en))


def icon(value):
    if value is None:
        return "null"
    if value.startswith("@"):
        name = snake(value[1:])
        if name in CAD_ICONS:
            return "ic(CadIcons.%s)" % name
        if name in CAD_ART:
            return "art(CadArt.%s)" % name
        missing.add("icon:" + value)
        return "null"
    if len(value) == 1 and 0xE000 <= ord(value) <= 0xF8FF:
        return 'RibbonIcon.glyph("\\u%04X")' % ord(value)
    return "RibbonIcon.text(%s)" % kstr(value)


def tip_text(text):
    """"Description\\n\\nCOMMAND" in Japanese (the command name at the end is kept)."""
    parts = text.split("\n\n")
    head = parts[0]
    translated = TIPS_JA.get(head)
    if translated is None:
        missing.add("tip:" + head)
        translated = head
    return "\n\n".join([translated] + parts[1:])


SIZES = {"Large": "RibbonItemSize.LARGE", "Medium": "RibbonItemSize.MEDIUM", "Small": "RibbonItemSize.SMALL"}


def size(el, default):
    return SIZES.get(el.get("Size"), default)


def tip_msg(key, text):
    """The ScreenTip description (English, and Japanese translated with the command name at the end kept)."""
    return msg(key, text, tip_text(text))


def screen_tip(el, owner):
    """The ScreenTip attribute or a child <RibbonScreenTip> ([owner] is the id of the item the text keys are based on)."""
    for child in el:
        if child.tag.endswith(".ScreenTip"):
            st = child[0]
            description = html.unescape(st.get("Description", ""))
            args = [label(owner + "|tip.title", st.get("Title")) if st.get("Title") else "null", tip_msg(owner + "|tip", description)]
            extra = []
            if st.get("ExtendedDescription"):
                extra.append("extendedDescription = %s" % tip_msg(owner + "|tip.extended", st.get("ExtendedDescription")))
            if st.get("ExtendedImage"):
                extra.append("extendedImage = %s" % icon(st.get("ExtendedImage")))
            if st.get("HelpText"):
                extra.append("helpText = %s" % tip_msg("tip|help", st.get("HelpText")))
            return "richTip(%s, %s)" % (", ".join(args), ", ".join(extra))
    if el.get("ScreenTip"):
        return "tip(%s)" % tip_msg(owner + "|tip", el.get("ScreenTip"))
    return None


def common(el, out, owner):
    """Settings common to items (KeyTip, shortcut, ScreenTip, label display)."""
    sets = []
    if el.get("KeyTip"):
        sets.append("it.keyTip = %s" % kstr(el.get("KeyTip")))
    if el.get("Shortcut"):
        sets.append("it.shortcut = %s" % kstr(el.get("Shortcut")))
    tip = screen_tip(el, owner)
    if tip:
        sets.append("it.screenTip = %s" % tip)
    if el.get("ShowLabel") == "False":
        sets.append("it.showLabel = false")
    if el.get("IsChecked") == "True":
        sets.append("it.isChecked = true")
    if el.get("GroupName"):
        sets.append("it.groupName = %s" % kstr(el.get("GroupName")))
    return out if not sets else out + ".also {\n" + "".join("    " + s + "\n" for s in sets) + "}"


def menu_entries(el, owner):
    """Items of a <MenuFlyout> (separators, radios, toggles)."""
    entries = []
    menu = None
    for child in el:
        if child.tag == "MenuFlyout":
            menu = child
        elif child.tag.endswith(".Flyout"):
            for c in child:
                if c.tag == "MenuFlyout":
                    menu = c
    if menu is None:
        return entries
    for index, item in enumerate(menu):
        if item.tag == "MenuFlyoutSeparator":
            entries.append("sep()")
            continue
        mid = "%s.%d" % (owner, index)
        text = label(mid, item.get("Text"), CONTEXT_JA.get((owner, item.get("Text"))))
        if item.tag == "RadioMenuFlyoutItem":
            entries.append("radioItem(%s, %s, %s, %s)" % (kstr(mid), text, kstr(item.get("GroupName")), "true" if item.get("IsChecked") == "True" else "false"))
        else:
            entries.append("mi(%s, %s, %s)" % (kstr(mid), text, icon(item.get("Tag"))))
    return entries


def combo(el):
    cid = el.get("Id")
    special = {
        "layerCombo": "layerCombo()",
        "objectColor": "colorCombo(\"objectColor\")",
        "teColor": "colorCombo(\"teColor\")",
        "hcColor": "colorCombo(\"hcColor\")",
        "objectLinetype": "linetypeCombo(\"objectLinetype\")",
        "objectLineweight": "lineweightCombo(\"objectLineweight\")",
    }
    if cid in special:
        return special[cid]
    texts = [s.text for s in el if s.tag == "x_String"]
    items = [label("%s|item.%d" % (cid, index), text) for index, text in enumerate(texts)]
    if el.get("Text"):
        text = el.get("Text")
        selected = items[texts.index(text)] if text in texts else label(cid + "|text", text)
    else:
        selected = items[0] if items else None
    args = [kstr(cid), label(cid + "|label", el.get("Label")) if el.get("Label") else "null", icon(el.get("Icon")),
            el.get("InputWidth", "120") + ".0", "true" if el.get("IsEditable") == "True" else "false",
            selected if selected else "null"] + items
    return common(el, "combo(%s)" % ", ".join(args), cid)


def item(el, depth=0):
    tag = el.tag
    iid = el.get("Id")
    owner = iid or el.get("Label")
    text = label(owner, el.get("Label"), CONTEXT_JA.get((iid, el.get("Label")))) if el.get("Label") is not None else None
    if tag == "RibbonButton":
        return common(el, "cmd(%s, %s, %s, %s)" % (kstr(iid or ja(el.get("Label"))), text, icon(el.get("Icon")), size(el, "RibbonItemSize.MEDIUM")), owner)
    if tag == "RibbonToggleButton":
        return common(el, "tgl(%s, %s, %s, %s)" % (kstr(iid), text, icon(el.get("Icon")), size(el, "RibbonItemSize.SMALL")), owner)
    if tag == "RibbonSplitButton":
        entries = menu_entries(el, iid)
        if not entries:
            entries = extra_menu(iid)
        follow = "true" if el.get("FollowLastChoice") == "True" else "false"
        args = [kstr(iid), text, icon(el.get("Icon")), size(el, "RibbonItemSize.MEDIUM"), follow] + entries
        return common(el, "spl(%s)" % ",\n".join(args), owner)
    if tag == "RibbonDropDownButton":
        entries = menu_entries(el, iid) or extra_menu(iid)
        args = [kstr(iid), text, icon(el.get("Icon")), size(el, "RibbonItemSize.MEDIUM")] + entries
        return common(el, "ddn(%s)" % ",\n".join(args), owner)
    if tag == "RibbonComboBox":
        return combo(el)
    if tag == "RibbonFontComboBox":
        return "fontCombo(%s, %s, %s.0)" % (kstr(iid), kstr(el.get("Text", "Arial")), el.get("InputWidth", "130"))
    if tag == "RibbonSlider":
        return "slider(%s, %s, %s, %s.0, %s)" % (kstr(iid), text, icon(el.get("Icon")), el.get("InputWidth", "120"), el.get("Value", "0") + ".0" if "." not in el.get("Value", "0") else el.get("Value"))
    if tag == "RibbonSpinner":
        value = el.get("Value", "0")
        return "spinner(%s, %s, %s.0, %s, %s)" % (kstr(iid), text, el.get("InputWidth", "70"), value if "." in value else value + ".0", kstr(el.get("Unit")) if el.get("Unit") else "null")
    if tag == "RibbonTextBox":
        return "textBox(%s, %s, %s.0)" % (kstr(iid), icon(el.get("Icon")), el.get("InputWidth", "140"))
    if tag == "RibbonStackPanel":
        vertical = "true" if el.get("Orientation") == "Vertical" else "false"
        children = [item(c, depth + 1) for c in el]
        return "stack(%s,\n%s)" % (vertical, ",\n".join(children))
    if tag == "RibbonButtonGroup":
        children = [item(c, depth + 1) for c in el]
        return "RibbonButtonGroupModel(\n%s)" % ",\n".join(children)
    if tag == "RibbonGallery":
        return gallery(el)
    if tag == "RibbonSeparator":
        return "RibbonSeparatorModel()"
    raise ValueError("unknown item: " + tag)


def gallery(el):
    gid = el.get("Id")
    items = []
    footer = []
    categories = []
    for child in el:
        if child.tag == "RibbonGalleryItem":
            category = child.get("Category")
            if category and category not in categories:
                categories.append(category)
            category_text = label("%s|category.%d" % (gid, categories.index(category)), category) if category else "null"
            items.append("gi(%s, %s, %s)" % (label("%s|item.%d" % (gid, len(items)), child.get("Label")), icon(child.get("Icon")), category_text))
        elif child.tag.endswith("FooterItems"):
            for index, f in enumerate(child):
                fid = "%s.footer%d" % (gid, index)
                footer.append("mi(%s, %s, %s)" % (kstr(fid), label(fid, f.get("Label")), icon(f.get("Icon"))))
    sets = []
    for attr, prop, conv in (("ItemWidth", "itemWidth", float), ("ItemHeight", "itemHeight", float), ("MinColumns", "minColumns", int),
                             ("MaxColumns", "maxColumns", int), ("DropDownColumns", "dropDownColumns", int), ("Rows", "rows", int),
                             ("MaxDropDownHeight", "maxDropDownHeight", float)):
        if el.get(attr):
            value = conv(el.get(attr))
            sets.append("g.%s = %s" % (prop, ("%s" % value) if conv is int else ("%s" % float(value))))
    if el.get("IsDropDownOnly") == "True":
        sets.append("g.isDropDownOnly = true")
    if el.get("ShowItemLabels") == "False":
        sets.append("g.showLabels = false")
    if el.get("KeyTip"):
        sets.append("g.keyTip = %s" % kstr(el.get("KeyTip")))
    tip = screen_tip(el, gid)
    if tip:
        sets.append("g.screenTip = %s" % tip)
    for f in footer:
        sets.append("g.menuItems.add(%s)" % f)
    body = "gallery(%s, %s, %s, %s,\n%s)" % (kstr(gid), label(gid, el.get("Label")), icon(el.get("Icon")), size(el, "RibbonItemSize.LARGE"), ",\n".join(items))
    if sets:
        body += ".also { g ->\n" + "".join("    " + s + "\n" for s in sets) + "}"
    return body


# Items whose translation depends on the place even for the same English ((item id, English) -> Japanese)
CONTEXT_JA = {
    ("arc", "Continue"): "継続",
    ("teCenter", "Center"): "中央揃え",
    ("teMatch", "Match"): "書式コピー",
    ("teLeft", "Left"): "左揃え",
    ("teRight", "Right"): "右揃え",
    ("leader", "Leader"): "引出線",
    ("adjust", "Adjust"): "調整",
}

# Items of dropdowns and split buttons that have no menu in the XAML (sequences of (English, Japanese); radios have a group name)
EXTRA_MENUS = {
    "teColumns": [("No Columns", "段組みなし"), ("Dynamic Columns", "ダイナミック段組み"), ("Static Columns", "静的段組み")],
    "teBullets": [("Off", "オフ"), ("Numbered", "番号付き"), ("Lettered", "英字"), ("Bulleted", "箇条書き")],
    "teLineSpacing": [("1.0x", "1.0x", "lineSpacing"), ("1.5x", "1.5x", "lineSpacing"), ("2.0x", "2.0x", "lineSpacing")],
    "hcMatch": [("Use Current Origin", "現在の原点を使用"), ("Use Source Hatch Origin", "ソースのハッチングの原点を使用")],
    "minimizeBehavior": [],
}


def extra_menu(owner):
    """The Kotlin expressions of the [EXTRA_MENUS] items (radios with the first item selected)."""
    entries = []
    for index, entry in enumerate(EXTRA_MENUS.get(owner, [])):
        mid = "%s.%d" % (owner, index)
        text = msg(mid, entry[0], entry[1])
        if len(entry) == 3:
            entries.append("radioItem(%s, %s, %s, %s)" % (kstr(mid), text, kstr(entry[2]), "true" if index == 0 else "false"))
        else:
            entries.append("mi(%s, %s, null)" % (kstr(mid), text))
    return entries


def group(el):
    gid = el.get("Id")
    children = [c for c in el if not c.tag.startswith("RibbonGroup.")]
    slide = [c for c in el if c.tag == "RibbonGroup.SlideOutItems"]
    items = [item(c) for c in children]
    sets = []
    if el.get("Icon"):
        sets.append("g.icon = %s" % icon(el.get("Icon")))
    if el.get("ScreenTip"):
        sets.append("g.description = %s" % tip_msg("group|%s|description" % gid, el.get("ScreenTip")))
    if el.get("ReductionOrder"):
        sets.append("g.reductionOrder = %s" % el.get("ReductionOrder"))
    if el.get("IsDialogLauncherVisible") == "True":
        sets.append("g.isDialogLauncherVisible = true")
    if el.get("ItemsLayout") == "Rows":
        sets.append("g.itemsLayout = RibbonGroupItemsLayout.ROWS")
    if el.get("RowCount"):
        sets.append("g.rowCount = %s" % el.get("RowCount"))
    for s in slide:
        for c in s:
            sets.append("g.slideOutItems.add(\n%s,\n)" % item(c))
    body = "group(%s, %s,\n%s)" % (kstr(gid), label("group|" + gid, el.get("Header")), ",\n".join(items))
    if sets:
        body += ".also { g ->\n" + "".join("    " + s + "\n" for s in sets) + "}"
    return body


