    tid = tab.get("Id")
    fname = re.sub(r"[^A-Za-z0-9]", "", tid)
    fname = (fname[:-3] if fname.endswith("Tab") else fname) + "Tab"
    groups = [group(g) for g in tab if g.tag == "RibbonGroup"]
    sets = []
    if tab.get("IsTabVisible") == "False":
        sets.append("t.isVisible = false")
    if tab.get("ContextualGroupId"):
        sets.append("t.contextualGroupId = %s" % kstr(tab.get("ContextualGroupId")))
    body = "tab(%s, %s, %s,\n%s)" % (kstr(tid), label("tab|" + tid, tab.get("Header")), kstr(tab.get("KeyTip")) if tab.get("KeyTip") else "null", ",\n".join(groups))
    if sets:
        body += ".also { t ->\n" + "".join("    " + s + "\n" for s in sets) + "}"
    functions.append(
        "/** The [%s] tab. */\n@Suppress(\"LongMethod\", \"CyclomaticComplexMethod\") // Declarative tab assembly generated from the XAML of the RibbonSpace CAD demo\nprivate fun %s(): RibbonTabModel = %s\n" % (ja(tab.get("Header")), fname, body)
    )
    tab_calls.append(fname + "()")

